#!/usr/bin/env python3
"""Draws a script's fixed words (its name, version, tags) as one picture, for Lib.Words.Use(manifest, url).

  python3 tools/gen_words.py <spec.json> <out dir>
spec.json: { "id": "qustah", "version": 1, "words": [ { "text": "Qustāh", "size": 16, "font": "x.ttf", "weight": 600,
             "glow": true }, ... ] }   (weight: for variable fonts)
writes <out dir>/<id>-words-v<version>.png and <id>-words.lua (the manifest). Each word is drawn white by FreeType
with hinting (letters fitted to whole pixels); with glow a blurred, widened copy is drawn too (tinted in Roblox).
"""
import json, math, pathlib, sys
from PIL import Image, ImageDraw, ImageFilter, ImageFont

spec = json.loads(pathlib.Path(sys.argv[1]).read_text())
out = pathlib.Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)
PAD = 8  # room round a word for its glow

def font(path, size, weight):
    f = ImageFont.truetype(path, size)
    try:
        if f.get_variation_axes() and weight: f.set_variation_by_axes([weight])
    except Exception:
        pass
    return f

pieces = []
for word in spec["words"]:
    f = font(word["font"], word["size"], word.get("weight"))
    text = word["text"]
    left, top, right, bottom = f.getbbox(text)
    ascent, descent = f.getmetrics()
    ink_w = math.ceil(f.getlength(text))
    w, h = ink_w + 2 * PAD, ascent + descent + 2 * PAD
    base = Image.new("L", (w, h), 0)
    ImageDraw.Draw(base).text((PAD, PAD), text, font=f, fill=255)
    entry = {"text": text, "size": word["size"], "w": w, "h": h, "ink": ink_w, "line": ascent + descent, "images": [base]}
    if word.get("glow"):
        glow = base.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(2.2))
        peak = max(glow.getextrema()[1], 1)
        entry["images"].append(glow.point(lambda v: min(255, int(v * 255 / peak))))
    pieces.append(entry)

width = max(p["w"] for p in pieces) * 2 + 2
y, rows = 0, []
for p in pieces:
    rows.append(y)
    y += p["h"] + 1
sheet = Image.new("RGBA", (width, y), (255, 255, 255, 0))
for p, row in zip(pieces, rows):
    for k, im in enumerate(p["images"]):
        rgba = Image.new("RGBA", im.size, (255, 255, 255, 0))
        rgba.putalpha(im)
        sheet.paste(rgba, (k * (p["w"] + 1), row))
name = f'{spec["id"]}-words-v{spec["version"]}.png'
sheet.save(out / name)
lines = [f'-- {spec["id"]} word pictures, generated by qustah-ui-lib tools/gen_words.py. Do not edit by hand.', "return {",
         f'    Id = "{spec["id"]}", Version = {spec["version"]}, File = "{name}", Pad = {PAD},',
         "    -- [text .. \"|\" .. size] = { x, y, w, h, ink width, line height, glow x (or nil) }", "    Words = {"]
for p, row in zip(pieces, rows):
    glow = str(p["w"] + 1) if len(p["images"]) > 1 else "nil"
    key = (p["text"] + "|" + str(p["size"])).replace('"', '\\"')
    lines.append(f'        ["{key}"] = {{ 0, {row}, {p["w"]}, {p["h"]}, {p["ink"]}, {p["line"]}, {glow} }},')
lines += ["    },", "}"]
(out / f'{spec["id"]}-words.lua').write_text("\n".join(lines) + "\n")
print(name, sheet.size, len(pieces), "words")
