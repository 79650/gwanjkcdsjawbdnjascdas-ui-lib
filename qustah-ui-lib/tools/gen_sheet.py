#!/usr/bin/env python3
"""Draws a script's own icon sheet: every listed lucide icon at every listed on-screen size, pixel for pixel,
so Roblox shows them without any scaling (the sharpest an icon can be). Used with Lib.Icons.UseSheet(manifest).

  python3 tools/gen_sheet.py <lucide icons dir> <id> <version> <names: a,b,c> <sizes: 7-22> <out dir>
writes <out dir>/<id>-<n>.png (pages up to 1024 x 1024) and <out dir>/<id>.lua (the manifest: page and place
of every size). Bump the version when the sheet changes: clients keep old files under the old name.

Small sizes are tuned rather than shrunk: lucide's 2 / 24 stroke would be under a pixel at 10 - 12 px (grey and
faint), so every size gets a stroke of at least 1.25 screen pixels; icons are drawn 4x larger and averaged down
(exact edge coverage).
"""
import json, os, re, subprocess, sys, tempfile, pathlib
from PIL import Image
SUPER = 4

icons_dir, sheet_id, version, names_arg, sizes_arg, out_dir = sys.argv[1:7]
icons_dir, out_dir = pathlib.Path(icons_dir), pathlib.Path(out_dir)
lo, hi = (int(x) for x in sizes_arg.split("-"))
sizes = list(range(lo, hi + 1))
have = {p.stem for p in icons_dir.glob("*.svg")}
alias = {}
for meta in icons_dir.glob("*.json"):
    try: data = json.loads(meta.read_text())
    except Exception: continue
    for entry in data.get("aliases", []):
        alias[entry["name"] if isinstance(entry, dict) else entry] = meta.stem
order = []
for name in [n for n in names_arg.split(",") if n]:
    src = name if name in have else alias.get(name)
    if src and name not in [n for n, _ in order]: order.append((name, src))
svgs = {src: re.sub(r"<!--.*?-->", "", (icons_dir / f"{src}.svg").read_text(), flags=re.S).replace("currentColor", "#ffffff") for _, src in order}

WIDTH = 1024
pages, layout, y, page = [[]], {}, 0, 0
for size in sizes:
    pitch = size + 2
    cols = WIDTH // pitch
    rows = (len(order) + cols - 1) // cols
    if y + rows * pitch > WIDTH:
        page, y = page + 1, 0
        pages.append([])
    layout[size] = (page + 1, y, cols)
    for i, (_, src) in enumerate(order):
        svg = svgs[src].replace('width="24"', f'width="{size}"').replace('height="24"', f'height="{size}"')
        stroke = max(1.25, size / 12) * 24 / size  # at least 1.25 screen pixels
        svg = svg.replace('stroke-width="2"', f'stroke-width="{stroke:.3f}"')
        pages[page].append(f'<div style="position:absolute;left:{(i % cols) * pitch + 1}px;top:{y + (i // cols) * pitch + 1}px;width:{size}px;height:{size}px">{svg}</div>')
    y += rows * pitch

out_dir.mkdir(parents=True, exist_ok=True)
tmp, jobs, files = tempfile.mkdtemp(), [], []
for k, cells in enumerate(pages, 1):
    name = f"{sheet_id}-{k}.png"
    height = max(layout[s][1] + ((len(order) + layout[s][2] - 1) // layout[s][2]) * (s + 2) for s in sizes if layout[s][0] == k)
    html = f'<html><body style="margin:0;background:transparent;width:{WIDTH}px;height:{height}px;position:relative">{"".join(cells)}</body></html>'
    path = os.path.join(tmp, name + ".html")
    open(path, "w").write(html)
    jobs.append([path, WIDTH, height, str(out_dir / name)])
    files.append(name)
script = """const {chromium}=require('playwright');(async()=>{const b=await chromium.launch();
for (const [f,w,h,o] of JSON.parse(process.argv[1])){const p=await b.newPage({viewport:{width:w,height:h},deviceScaleFactor:0});
await p.goto('file://'+f);await p.waitForTimeout(300);await p.screenshot({path:o,omitBackground:true,clip:{x:0,y:0,width:w,height:h}});await p.close();}
await b.close();})();"""
subprocess.run(["node", "-e", script.replace("deviceScaleFactor:0", f"deviceScaleFactor:{SUPER}"), json.dumps(jobs)], check=True)
for _, w, h, out in jobs:
    big = Image.open(out).convert("RGBA")
    alpha = big.getchannel("A").resize((w, h), Image.BOX)  # white icons: only coverage matters
    Image.merge("RGBA", (Image.new("L", (w, h), 255),) * 3 + (alpha,)).save(out, optimize=True)
lua = [f"-- {sheet_id} icon sheet manifest, generated by qustah-ui-lib tools/gen_sheet.py. Do not edit by hand.",
       "return {",
       f'    Id = "{sheet_id}", Version = {int(version)},',
       "    Files = { " + ", ".join(f'"{f}"' for f in files) + " },",
       '    Names = "' + ",".join(n for n, _ in order) + '",',
       "    Sizes = {"]
for size in sizes:
    p, y0, cols = layout[size]
    lua.append(f"        [{size}] = {{ {p}, {y0}, {cols} }},")
lua += ["    },", "}", ""]
(out_dir / f"{sheet_id}.lua").write_text("\n".join(lua))
print(len(order), "icons,", len(sizes), "sizes,", len(files), "page(s)")
