#!/usr/bin/env python3
"""Draws the sharp lucide sheets: icons/atlas/lucide-16.png (one page) and lucide-32-1/2.png, plus src/icons_atlas.lua
(the order of the icons in the sheets). Roblox shrinks a big icon image badly (it skips pixels), so the library shows
lucide icons from these small sheets through getcustomasset: the 16 px sheet for icons up to 16 px on screen, the
32 px sheets above that (never more than 2x smaller, which Roblox's filter handles cleanly).

Needs a lucide checkout and Playwright:
  git clone --depth 1 --filter=blob:none --sparse https://github.com/lucide-icons/lucide.git /tmp/lucide
  (cd /tmp/lucide && git sparse-checkout set icons)
  python3 tools/gen_atlas.py /tmp/lucide/icons
Bump VERSION when the sheets change: clients keep the old files under the old version name.
"""
import json, os, pathlib, re, subprocess, sys, tempfile

VERSION = 1
SHEETS = {16: 56, 32: 30}          # cell size -> columns; 1 px of empty gutter around every cell
PER_PAGE = {16: 10000, 32: 900}    # 32 px pages stay under 1024 x 1024

ROOT = pathlib.Path(__file__).resolve().parent.parent
icons_dir = pathlib.Path(sys.argv[1])
names = re.findall(r'\["([^"]+)"\]=\d+', (ROOT / "src" / "icons_lucide.lua").read_text())
have = {p.stem for p in icons_dir.glob("*.svg")}
alias = {}
for meta in icons_dir.glob("*.json"):
    try: data = json.loads(meta.read_text())
    except Exception: continue
    for entry in data.get("aliases", []):
        alias[entry["name"] if isinstance(entry, dict) else entry] = meta.stem
order = [(n, n if n in have else alias.get(n)) for n in names]
order = [(n, s) for n, s in order if s]

def page_html(size, items, cols):
    pitch = size + 2
    rows = (len(items) + cols - 1) // cols
    cells = []
    for i, (_, src) in enumerate(items):
        svg = re.sub(r"<!--.*?-->", "", (icons_dir / f"{src}.svg").read_text(), flags=re.S)
        svg = svg.replace("currentColor", "#ffffff").replace('width="24"', f'width="{size}"').replace('height="24"', f'height="{size}"')
        x, y = (i % cols) * pitch + 1, (i // cols) * pitch + 1
        cells.append(f'<div style="position:absolute;left:{x}px;top:{y}px;width:{size}px;height:{size}px">{svg}</div>')
    w, h = cols * pitch, rows * pitch
    return f'<html><body style="margin:0;background:transparent;width:{w}px;height:{h}px;position:relative">{"".join(cells)}</body></html>', w, h

out_dir = ROOT / "icons" / "atlas"
out_dir.mkdir(parents=True, exist_ok=True)
jobs, tmp = [], tempfile.mkdtemp()
for size, cols in SHEETS.items():
    per = PER_PAGE[size]
    pages = [order[i:i + per] for i in range(0, len(order), per)]
    for k, items in enumerate(pages, 1):
        name = f"lucide-{size}.png" if len(pages) == 1 else f"lucide-{size}-{k}.png"
        html, w, h = page_html(size, items, cols)
        path = os.path.join(tmp, name + ".html")
        open(path, "w").write(html)
        jobs.append([path, w, h, str(out_dir / name)])
script = """const {chromium}=require('playwright');(async()=>{const b=await chromium.launch();
for (const [f,w,h,o] of JSON.parse(process.argv[1])){const p=await b.newPage({viewport:{width:w,height:h},deviceScaleFactor:1});
await p.goto('file://'+f);await p.waitForTimeout(300);await p.screenshot({path:o,omitBackground:true,clip:{x:0,y:0,width:w,height:h}});await p.close();}
await b.close();})();"""
subprocess.run(["node", "-e", script, json.dumps(jobs)], check=True)

lua = ["-- Order of the icons in icons/atlas/*.png, generated by tools/gen_atlas.py. Do not edit by hand.",
       "return {",
       f"    Version = {VERSION},",
       "    Sheets = { [16] = { Columns = %d, PerPage = %d }, [32] = { Columns = %d, PerPage = %d } }," % (SHEETS[16], PER_PAGE[16], SHEETS[32], PER_PAGE[32]),
       "    Pages = { [16] = { \"%s\" }, [32] = { %s } }," % (
           "lucide-16.png",
           ", ".join(f'"lucide-32-{k}.png"' for k in range(1, (len(order) + PER_PAGE[32] - 1) // PER_PAGE[32] + 1))),
       "    Names = \"" + ",".join(n for n, _ in order) + "\",",
       "}", ""]
(ROOT / "src" / "icons_atlas.lua").write_text("\n".join(lua))
print(len(order), "icons;", len(jobs), "sheets")
